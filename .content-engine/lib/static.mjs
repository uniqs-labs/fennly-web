// The site's own files (landing page, legal pages, assets). They are copied into dist/
// byte for byte; the build never rewrites them.
import fs from 'node:fs';
import path from 'node:path';
import { PREVIEW_DIR } from './config.mjs';

// Top-level entries that belong to the repository or the build, not to the website.
export const NOT_STATIC = new Set([
  'node_modules', 'dist', 'content', 'package.json', 'package-lock.json', 'npm-shrinkwrap.json',
  'yarn.lock', 'pnpm-lock.yaml', 'vercel.json', 'content.config.json', 'README.md', 'CLAUDE.md',
  'AGENTS.md', 'LICENSE', 'LICENSE.md', 'Thumbs.db',
]);
// Files the build writes itself. A static file with the same name would silently lose.
export const GENERATED_FILES = ['sitemap.xml', 'robots.txt', 'llms.txt'];

/** Every static file as a POSIX path relative to root, sorted. */
export function listStatic(root, extraExclude = []) {
  const extra = new Set(extraExclude.map((p) => p.replace(/^\/+|\/+$/g, '')));
  const out = [];
  const walk = (dir, rel) => {
    for (const name of fs.readdirSync(dir).sort()) {
      const relPath = rel ? `${rel}/${name}` : name;
      // Dotfiles and dot-directories (.git, .content-engine, .vercel, .DS_Store) never ship,
      // except the standard /.well-known/ directory.
      if (name.startsWith('.') && !(rel === '' && name === '.well-known')) continue;
      if (rel === '' && NOT_STATIC.has(name)) continue;
      if (extra.has(relPath)) continue;
      const full = path.join(dir, name);
      const stat = fs.lstatSync(full);
      if (stat.isSymbolicLink()) continue;
      if (stat.isDirectory()) walk(full, relPath);
      else if (stat.isFile()) out.push(relPath);
    }
  };
  walk(root, '');
  return out;
}

/** Problems with static files that would collide with generated output. */
export function staticConflicts(files, generatedPaths) {
  const problems = [];
  const generated = new Set(generatedPaths);
  for (const f of files) {
    if (GENERATED_FILES.includes(f)) {
      problems.push(`${f} is generated by the build now; delete it from the repo (settings live in content.config.json)`);
    } else if (f === PREVIEW_DIR || f.startsWith(`${PREVIEW_DIR}/`)) {
      problems.push(`${f}: /${PREVIEW_DIR}/ is reserved for draft previews`);
    } else if (generated.has(f)) {
      problems.push(`${f} collides with a generated page; rename or move one of them`);
    }
  }
  return problems;
}

export function copyStatic(root, outDir, files) {
  for (const f of files) {
    const dest = path.join(outDir, f);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(path.join(root, f), dest);
  }
}

/** URL path of a static HTML file: "privacy/index.html" -> "/privacy/", "a.html" -> "/a.html". */
export function htmlUrlPath(file) {
  if (file === 'index.html') return '/';
  if (file.endsWith('/index.html')) return `/${file.slice(0, -'index.html'.length)}`;
  return `/${file}`;
}

const NOINDEX_RE = /<meta\s[^>]*name=["']robots["'][^>]*content=["'][^"']*noindex/i;
const NOINDEX_RE2 = /<meta\s[^>]*content=["'][^"']*noindex[^"']*["'][^>]*name=["']robots["']/i;

/** Static HTML pages with their URL path and whether they opt out of indexing. */
export function staticPages(root, files) {
  return files
    .filter((f) => f.endsWith('.html') && f !== '404.html')
    .map((f) => {
      const head = fs.readFileSync(path.join(root, f), 'utf8').slice(0, 20000);
      return { file: f, path: htmlUrlPath(f), noindex: NOINDEX_RE.test(head) || NOINDEX_RE2.test(head) };
    });
}
