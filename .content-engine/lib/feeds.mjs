// sitemap.xml, robots.txt and llms.txt.
import { esc } from './html.mjs';
import { hostOf } from './attribution.mjs';

/**
 * Sitemap entries: indexable static pages (with the per-page settings from
 * content.config.json), hubs that have live articles, and every live article.
 */
export function sitemapEntries({ config, pages, hubs, articles }) {
  const url = config.url;
  const exclude = new Set(config.sitemap.exclude || []);
  const entries = [];
  const statics = pages
    .filter((p) => !p.noindex && !exclude.has(p.path))
    .sort((a, b) => (a.path === '/' ? -1 : b.path === '/' ? 1 : a.path.localeCompare(b.path)));
  for (const p of statics) {
    const meta = config.sitemap.pages?.[p.path] || {};
    entries.push({ loc: url.abs(p.path), lastmod: meta.lastmod, changefreq: meta.changefreq, priority: meta.priority });
  }
  for (const h of hubs) {
    entries.push({ loc: url.abs(h.path), lastmod: h.lastmod, changefreq: 'weekly', priority: '0.7' });
  }
  for (const a of articles) {
    entries.push({ loc: url.abs(a.path), lastmod: a.reviewed, changefreq: 'monthly', priority: '0.6' });
  }
  return entries;
}

export function sitemapXml(entries) {
  const urls = entries.map((e) => [
    '  <url>',
    `    <loc>${esc(e.loc)}</loc>`,
    e.lastmod ? `    <lastmod>${e.lastmod}</lastmod>` : null,
    e.changefreq ? `    <changefreq>${e.changefreq}</changefreq>` : null,
    e.priority !== undefined && e.priority !== null ? `    <priority>${Number(e.priority).toFixed(1)}</priority>` : null,
    '  </url>',
  ].filter(Boolean).join('\n'));
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`;
}

export function robotsTxt(config) {
  const agents = config.robots.allow?.length ? config.robots.allow : ['*'];
  const disallow = config.robots.disallow || [];
  const lines = [`# ${hostOf(config.origin)}`, '# Generated by the content engine from content.config.json (robots).', ''];
  agents.forEach((agent, i) => {
    if (i === 1 && agent !== '*') lines.push('# AI and search crawlers, explicitly allowed.', '');
    lines.push(`User-agent: ${agent}`, 'Allow: /');
    for (const d of disallow) lines.push(`Disallow: ${d}`);
    lines.push('');
  });
  lines.push(`Sitemap: ${config.url.abs('/sitemap.xml')}`, '');
  return lines.join('\n');
}

/** llms.txt (llmstxt.org): what the site is and where the substantial pages are. */
export function llmsTxt({ config, articles, hubs, pages }) {
  const url = config.url;
  const st = config.strings;
  const first = config.languages.includes(config.xDefault) ? config.xDefault : config.languages[0];
  const lines = [`# ${config.brand.name}`, '', `> ${config.copy[first].tagline}`, ''];
  for (const lang of config.languages) {
    if (lang !== first) lines.push(`${config.copy[lang].tagline}`, '');
  }
  const exclude = new Set(config.sitemap.exclude || []);
  for (const lang of config.languages) {
    for (const type of config.types) {
      const list = articles.filter((a) => a.lang === lang && a.type === type);
      if (!list.length) continue;
      const hub = hubs.find((h) => h.lang === lang && h.type === type);
      lines.push(`## ${st[lang].section[type] || type} (${lang})`, '');
      if (hub) lines.push(`- [${config.copy[lang].hubs[type].title}](${url.abs(hub.path)}): ${config.copy[lang].hubs[type].description}`);
      for (const a of list) lines.push(`- [${a.title}](${url.abs(a.path)}): ${a.description}`);
      lines.push('');
    }
  }
  const statics = pages.filter((p) => !p.noindex && !exclude.has(p.path));
  if (statics.length) {
    lines.push('## Pages', '');
    for (const p of statics) {
      const legal = config.legal.find((l) => l.href === p.path);
      const name = p.path === '/' ? config.brand.name : legal ? legal.label[first] : p.path;
      lines.push(`- [${name}](${url.abs(p.path)})`);
    }
    lines.push('');
  }
  return lines.join('\n');
}
